-- Run this in Supabase Dashboard > SQL Editor > New query.
-- Public visitors can submit pending messages and read approved messages only.
-- They cannot approve, edit, or delete messages.

create table if not exists public.guestbook_messages (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 60),
  message text not null check (char_length(message) between 1 and 500),
  approved boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.guestbook_messages enable row level security;

revoke all on table public.guestbook_messages from anon, authenticated;
grant select, insert on table public.guestbook_messages to anon;
grant select, insert on table public.guestbook_messages to authenticated;
grant usage, select on sequence public.guestbook_messages_id_seq to anon, authenticated;

drop policy if exists "Anyone can read approved guestbook messages" on public.guestbook_messages;
create policy "Anyone can read approved guestbook messages"
on public.guestbook_messages
for select
to anon, authenticated
using (approved = true);

drop policy if exists "Anyone can submit pending guestbook messages" on public.guestbook_messages;
create policy "Anyone can submit pending guestbook messages"
on public.guestbook_messages
for insert
to anon, authenticated
with check (
  approved = false
  and char_length(trim(name)) between 1 and 60
  and char_length(trim(message)) between 1 and 500
);

-- Do not create public UPDATE or DELETE policies.
-- To approve a message: Supabase > Table Editor > guestbook_messages > edit approved to true.
-- To remove a message: delete its row in Table Editor.
